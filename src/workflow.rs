//! The commit workflow: preflight, collect changes, ask the model, apply proposals.
//! No terminal output happens here; both the TUI and the non-interactive CLI drive it.

use std::path::PathBuf;

use crate::changes::{ChangeSet, Origin};
use crate::config::Config;
use crate::git::patch::PatchError;
use crate::git::{
    parse_patch, CommitInfo, CommitMode, EntryKind, FileKind, FilePatch, GitError, GitRepo,
    InProgress, RepoState,
};
use crate::llm::{LlmError, ProposeRequest, Proposer, RulesRequest};
use crate::prompts::system_prompt;
use crate::proposal::ProposalResult;
use crate::rules::{
    build_rules_context, render_history, DerivedRules, HistoryContext, RULES_SYSTEM_PROMPT,
};

pub const WATERMARK: &str = "Commit generated by VibeGit";
pub const RULES_FILENAME: &str = ".vibegitrules";
/// Untracked files above this size are skipped entirely (they would be hashed and diffed in full).
const MAX_UNTRACKED_BYTES: u64 = 50 * 1024 * 1024;

#[derive(Debug, thiserror::Error)]
pub enum WorkflowError {
    #[error(transparent)]
    Git(#[from] GitError),
    #[error("could not parse git's diff output: {0}")]
    Patch(#[from] PatchError),
    #[error(transparent)]
    Io(#[from] std::io::Error),
    #[error(transparent)]
    Llm(#[from] LlmError),
    #[error("a {} is in progress; {} before running VibeGit", .0.name(), .0.resolve_hint())]
    InProgress(InProgress),
    #[error("the repository has unmerged paths ({}); resolve the conflicts first", .0.join(", "))]
    Conflicts(Vec<String>),
    #[error("the index already contains staged changes; VibeGit refuses to stack a commit on top of them")]
    IndexDirty,
    #[error("the model's proposals do not match the changes: {0}")]
    Changes(#[from] crate::changes::ChangeError),
    #[error("commit failed: {source}")]
    Commit {
        #[source]
        source: GitError,
    },
    #[error("the repository has no commits to learn from yet")]
    NoHistory,
}

pub type WorkflowResult<T> = Result<T, WorkflowError>;

#[derive(Debug, Clone)]
pub struct Preflight {
    pub state: RepoState,
    /// Paths with staged changes; VibeGit needs an index that equals HEAD.
    pub staged: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Leftover {
    pub changed: usize,
    pub untracked: usize,
    pub staged: usize,
}

impl Leftover {
    pub fn is_clean(&self) -> bool {
        self.changed == 0 && self.untracked == 0 && self.staged == 0
    }
}

pub struct Workflow {
    pub repo: GitRepo,
    pub config: Config,
    pub proposer: Box<dyn Proposer>,
    pub project_instructions: Option<String>,
    /// When set, prompts and responses are written here for troubleshooting.
    pub debug_dir: Option<PathBuf>,
}

impl Workflow {
    pub fn new(repo: GitRepo, config: Config, proposer: Box<dyn Proposer>) -> Self {
        let project_instructions = read_project_instructions(&repo);
        Self {
            repo,
            config,
            proposer,
            project_instructions,
            debug_dir: None,
        }
    }

    /// Checks the repository state before anything is written.
    pub fn preflight(&self) -> WorkflowResult<Preflight> {
        let state = self.repo.state()?;
        if let Some(p) = state.in_progress {
            return Err(WorkflowError::InProgress(p));
        }
        let entries = self.repo.status()?;
        let unmerged: Vec<String> = entries
            .iter()
            .filter(|e| e.kind == EntryKind::Unmerged)
            .map(|e| e.path.clone())
            .collect();
        if !unmerged.is_empty() {
            return Err(WorkflowError::Conflicts(unmerged));
        }
        let staged = entries
            .iter()
            .filter(|e| e.is_staged() || e.is_intent_to_add())
            .map(|e| e.path.clone())
            .collect();
        Ok(Preflight { state, staged })
    }

    pub fn unstage_all(&self) -> WorkflowResult<()> {
        self.repo.unstage_all()?;
        Ok(())
    }

    /// Collects every uncommitted change into numbered change units.
    pub fn collect(&self) -> WorkflowResult<ChangeSet> {
        let mut set = ChangeSet::new();
        let mut warnings = Vec::new();
        let entries = self.repo.status()?;
        let max_bytes = self
            .config
            .context_formatting
            .max_file_size_kb
            .saturating_mul(1024);

        let diff = self.repo.diff_tracked()?;
        for file in parse_patch(&diff)? {
            let placeholder = if file.kind == FileKind::Submodule {
                Some(self.submodule_summary(&file))
            } else if !file.binary && file.raw.len() as u64 > max_bytes {
                Some(format!(
                    "<diff omitted: {} KB, above context_formatting.max_file_size_kb>",
                    file.raw.len() / 1024
                ))
            } else {
                None
            };
            set.add_file(file, Origin::Tracked, placeholder);
        }

        for entry in &entries {
            if let Some(sub) = entry.submodule {
                if sub.tracked_modified || sub.has_untracked {
                    warnings.push(format!(
                        "submodule {} has uncommitted changes inside it; commit them in the submodule first",
                        entry.path
                    ));
                }
            }
            match entry.kind {
                EntryKind::NestedRepo => warnings.push(format!(
                    "{} is a nested git repository and was skipped (use `git submodule add` to track it)",
                    entry.path
                )),
                EntryKind::Untracked => {
                    let full = self.repo.root().join(&entry.path);
                    let size = std::fs::symlink_metadata(&full).map(|m| m.len()).unwrap_or(0);
                    if size > MAX_UNTRACKED_BYTES {
                        warnings.push(format!(
                            "{} is {} MB and was skipped; add it with `git add` if it belongs in the repository",
                            entry.path,
                            size / 1024 / 1024
                        ));
                        continue;
                    }
                    let diff = match self.repo.diff_untracked(&entry.path) {
                        Ok(d) => d,
                        Err(err) => {
                            warnings.push(format!("{}: {}", entry.path, err));
                            continue;
                        }
                    };
                    for file in parse_patch(&diff)? {
                        let placeholder = if !file.binary && size > max_bytes {
                            Some(format!(
                                "<content omitted: {} KB, above context_formatting.max_file_size_kb>",
                                size / 1024
                            ))
                        } else {
                            None
                        };
                        set.add_file(file, Origin::Untracked, placeholder);
                    }
                }
                _ => {}
            }
        }
        set.warnings = warnings;
        Ok(set)
    }

    fn submodule_summary(&self, file: &FilePatch) -> String {
        match file.submodule_commits() {
            Some((Some(old), Some(new))) => {
                let mut lines = vec![format!("Subproject commit {old} -> {new}")];
                let log = self.repo.submodule_log(&file.path, &old, &new);
                if !log.is_empty() {
                    lines.push("New commits in the submodule:".to_string());
                    lines.extend(log.iter().map(|l| format!("  {l}")));
                }
                lines.join("\n")
            }
            Some((None, Some(new))) => format!("Submodule added at commit {new}"),
            Some((Some(old), None)) => format!("Submodule removed (was at commit {old})"),
            _ => "Submodule changed".to_string(),
        }
    }

    /// The user message sent to the model.
    pub fn build_context(
        &self,
        changes: &ChangeSet,
        instruction: Option<&str>,
    ) -> WorkflowResult<String> {
        let cf = &self.config.context_formatting;
        let mut parts: Vec<String> = Vec::new();
        if cf.include_active_branch {
            let state = self.repo.state()?;
            parts.push(format!("Active Branch: {}", state.describe_head()));
        }
        if let Some(n) = cf.include_latest_commits.filter(|n| *n > 0) {
            let messages = self.repo.recent_commit_messages(n)?;
            if !messages.is_empty() {
                let mut lines = vec!["Latest Commits:".to_string()];
                for (i, m) in messages.iter().enumerate() {
                    lines.push(format!("{}. {}", i + 1, format_history_message(m)));
                }
                parts.push(lines.join("\n"));
            }
        }
        if let Some(p) = self
            .project_instructions
            .as_deref()
            .map(str::trim)
            .filter(|p| !p.is_empty())
        {
            parts.push(format!("Project Instructions: \"{p}\""));
        }
        if let Some(i) = instruction.map(str::trim).filter(|i| !i.is_empty()) {
            parts.push(format!("User Instructions (priority): \"{i}\""));
        }
        parts.push(changes.render_for_model(cf.truncate_lines));
        Ok(parts.join("\n\n"))
    }

    /// Asks the model for proposals and validates them against the change set.
    pub fn propose(
        &self,
        changes: &ChangeSet,
        instruction: Option<&str>,
    ) -> WorkflowResult<ProposalResult> {
        let system = system_prompt(self.config.allow_excluding_changes);
        let user = self.build_context(changes, instruction)?;
        self.debug_dump("prompt.txt", &format!("{system}\n\n=== USER ===\n\n{user}"));
        let validate = |r: &ProposalResult| changes.validate(r).map_err(|e| e.to_string());
        let result = self.proposer.propose(ProposeRequest {
            system: &system,
            user: &user,
            allow_excluding: self.config.allow_excluding_changes,
            validate: &validate,
        });
        if let Err(e) = &result {
            self.debug_dump("error.txt", &e.to_string());
        }
        let result = result?;
        changes.validate(&result)?;
        self.debug_dump(
            "response.json",
            &serde_json::to_string_pretty(&result).unwrap_or_default(),
        );
        Ok(result)
    }

    /// Stages exactly the given change units and commits them.
    pub fn apply(
        &self,
        changes: &mut ChangeSet,
        ids: &[u32],
        message: &str,
        mode: CommitMode,
    ) -> WorkflowResult<CommitInfo> {
        if !self.repo.index_matches_base()? {
            return Err(WorkflowError::IndexDirty);
        }
        let patch = changes.patch_for(ids)?;
        self.repo.apply_cached(&patch)?;
        let message = self.final_message(message);
        match self.repo.commit(&message, mode) {
            Ok(info) => {
                changes.mark_applied(ids);
                Ok(info)
            }
            Err(source) => {
                let _ = self.repo.unstage_paths(&changes.paths_for(ids));
                Err(WorkflowError::Commit { source })
            }
        }
    }

    pub fn push(&self, inherit: bool) -> WorkflowResult<String> {
        Ok(self.repo.push(inherit)?)
    }

    pub fn leftover(&self) -> WorkflowResult<Leftover> {
        let entries = self.repo.status()?;
        let mut left = Leftover::default();
        for e in &entries {
            match e.kind {
                EntryKind::Untracked => left.untracked += 1,
                EntryKind::Ordinary | EntryKind::Rename => {
                    if e.is_staged() {
                        left.staged += 1;
                    }
                    if e.is_worktree_changed() {
                        left.changed += 1;
                    }
                }
                _ => {}
            }
        }
        Ok(left)
    }

    // --- project rules ---------------------------------------------------------

    pub fn rules_path(&self) -> PathBuf {
        self.repo.root().join(RULES_FILENAME)
    }

    pub fn has_rules(&self) -> bool {
        self.rules_path().exists()
    }

    /// The reduced history rendering that rule derivation sends to the model.
    pub fn history_context(&self) -> WorkflowResult<HistoryContext> {
        render_history(
            &self.repo,
            &self.config.init,
            self.config.context_formatting.truncate_lines,
        )
    }

    /// Asks the model to describe the repository's commit conventions as `.vibegitrules`.
    pub fn derive_rules(&self) -> WorkflowResult<DerivedRules> {
        let history = self.history_context()?;
        let state = self.repo.state()?;
        let repo_name = self
            .repo
            .root()
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_else(|| "repository".into());
        let user = build_rules_context(&repo_name, &state.describe_head(), &history);
        self.debug_dump(
            "rules-prompt.txt",
            &format!(
                "{RULES_SYSTEM_PROMPT}

=== USER ===

{user}"
            ),
        );
        let result = self.proposer.derive_rules(RulesRequest {
            system: RULES_SYSTEM_PROMPT,
            user: &user,
        });
        if let Err(e) = &result {
            self.debug_dump("rules-error.txt", &e.to_string());
        }
        let mut derived = result?;
        derived.rules = derived.rules.trim().to_string();
        derived.observations.retain(|o| !o.trim().is_empty());
        self.debug_dump(
            "rules-response.json",
            &serde_json::to_string_pretty(&derived).unwrap_or_default(),
        );
        Ok(derived)
    }

    /// Writes `.vibegitrules` and starts using it for this session.
    pub fn write_rules(&mut self, text: &str) -> WorkflowResult<PathBuf> {
        let path = self.rules_path();
        let mut content = text.trim_end().to_string();
        content.push('\n');
        std::fs::write(&path, &content)?;
        self.project_instructions = Some(content).filter(|c| !c.trim().is_empty());
        Ok(path)
    }

    /// The message as committed: trimmed, normalised, optionally watermarked.
    pub fn final_message(&self, message: &str) -> String {
        let mut text = sanitize_message(message);
        if self.config.watermark {
            text.push_str("\n\n");
            text.push_str(WATERMARK);
        }
        text
    }

    fn debug_dump(&self, name: &str, content: &str) {
        if let Some(dir) = &self.debug_dir {
            if std::fs::create_dir_all(dir).is_ok() {
                let _ = std::fs::write(dir.join(name), content);
            }
        }
    }
}

fn read_project_instructions(repo: &GitRepo) -> Option<String> {
    let path = repo.root().join(RULES_FILENAME);
    std::fs::read_to_string(path)
        .ok()
        .filter(|s| !s.trim().is_empty())
}

/// Trims trailing whitespace and collapses runs of blank lines.
pub fn sanitize_message(message: &str) -> String {
    let mut out: Vec<&str> = Vec::new();
    let mut blank_run = 0;
    for line in message.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            blank_run += 1;
            if blank_run > 1 || out.is_empty() {
                continue;
            }
        } else {
            blank_run = 0;
        }
        out.push(line);
    }
    while out.last().is_some_and(|l| l.is_empty()) {
        out.pop();
    }
    out.join("\n")
}

/// History entries as shown to the model: watermark removed, quoted, continuation indented.
fn format_history_message(message: &str) -> String {
    let cleaned = message.replace(WATERMARK, "");
    let cleaned = cleaned.trim();
    let lines: Vec<String> = cleaned
        .lines()
        .enumerate()
        .map(|(i, l)| {
            if i == 0 {
                l.to_string()
            } else {
                format!("   {l}")
            }
        })
        .collect();
    format!("\"{}\"", lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitizes_messages() {
        assert_eq!(
            sanitize_message("  subject  \n\n\n\nbody \n\n"),
            "  subject\n\nbody"
        );
        assert_eq!(sanitize_message("\n\nx"), "x");
    }

    #[test]
    fn formats_history() {
        let m = format!("subject\n\nbody line\n\n{WATERMARK}");
        assert_eq!(format_history_message(&m), "\"subject\n   \n   body line\"");
    }
}
