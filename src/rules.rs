//! Deriving `.vibegitrules` from the repository's own history.
//!
//! The recent commits are rendered like the grouping context (message, file
//! summaries, hunks) but with far less detail per file, and a dedicated prompt
//! asks the model to describe the conventions it sees as rules for the
//! commit assistant.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

use crate::config::InitConfig;
use crate::git::{parse_patch, FileKind, FilePatch, GitRepo, HistoryCommit};
use crate::proposal::extract_json;
use crate::workflow::{WorkflowError, WorkflowResult, WATERMARK};

/// What the model returns.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Default)]
pub struct DerivedRules {
    #[serde(default)]
    pub observations: Vec<String>,
    #[serde(default)]
    pub rules: String,
}

/// The rendered history that is sent to the model.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HistoryContext {
    pub commits_available: usize,
    pub commits_included: usize,
    pub text: String,
}

pub const RULES_SYSTEM_PROMPT: &str = r#"You are an expert in software engineering practice who documents how a team uses Git. You will receive excerpts from a repository's recent commit history: for each commit its message, the date, and an abbreviated diff (a summary line per file followed by a few diff lines). Your task is to infer the project's commit conventions and write the content of a `.vibegitrules` file.

That file is read by an AI assistant which turns a developer's uncommitted changes into a series of commits: it groups related hunks and writes a commit message for each group. The rules must tell that assistant, concretely and briefly, how commits in this repository should look and how changes should be grouped.

Analyze the history along these dimensions:

1. **Message format:** structure of the subject line (prefixes such as Conventional Commits types, scopes, ticket references, emoji), capitalisation, mood (imperative or past tense), typical length, trailing punctuation, language; whether bodies or trailers are used and what they contain.
2. **Granularity:** how much a commit typically contains (one small logical change, a whole feature, mixed concerns) and whether tests, documentation, formatting, dependency or configuration changes ship together with the code they relate to or separately.
3. **Grouping and ordering:** how changes spanning several files are combined, and in which order related commits tend to appear (for example refactoring before the feature that needs it, tests after the code).
4. **Exclusions and special cases:** anything the history suggests should stay out of commits or be handled on its own (generated files, lockfiles, secrets, debug output, large binaries).

Then write the rules:

- Address the assistant directly in the imperative ("Use ...", "Group ...", "Keep ...", "Do not ...").
- Be specific: state the exact subject-line format as a short pattern or template, and quote two or three real subject lines from the history as examples.
- Only include rules the history actually supports. If the history is thin or inconsistent, say so in the observations and keep the rules minimal instead of inventing conventions.
- Keep the file between roughly 80 and 300 words of plain text. Short paragraphs or lines starting with "- " are fine; no headings, no code fences, no JSON inside the rules text.
- Do not mention VibeGit or this analysis, and never ask for trailers such as "Commit generated by VibeGit"; such lines are added automatically and are not part of the conventions.

Respond with a JSON object of this shape and nothing else:

{
  "observations": ["three to six findings about the observed conventions, one sentence each"],
  "rules": "the complete content of the .vibegitrules file"
}"#;

pub fn rules_schema() -> Value {
    json!({
        "type": "object",
        "properties": {
            "observations": {
                "type": "array",
                "description": "Three to six one-sentence findings about the observed conventions.",
                "items": {"type": "string"}
            },
            "rules": {
                "type": "string",
                "description": "The complete content of the .vibegitrules file."
            }
        },
        "required": ["observations", "rules"]
    })
}

pub fn parse_rules_response(text: &str) -> Result<DerivedRules, String> {
    let value = extract_json(text)?;
    let parsed: DerivedRules =
        serde_json::from_value(value).map_err(|e| format!("unexpected response shape: {e}"))?;
    if parsed.rules.trim().is_empty() {
        return Err("the rules text is empty".into());
    }
    Ok(parsed)
}

/// Renders the recent history with reduced per-file detail.
pub fn render_history(
    repo: &GitRepo,
    cfg: &InitConfig,
    truncate: Option<usize>,
) -> WorkflowResult<HistoryContext> {
    let commits_available = repo.commit_count();
    if commits_available == 0 {
        return Err(WorkflowError::NoHistory);
    }
    let commits = repo.history(cfg.commits.max(1))?;
    let budget = cfg.max_total_kb.saturating_mul(1024) as usize;
    let mut sections: Vec<String> = Vec::new();
    let mut extensions: BTreeMap<String, usize> = BTreeMap::new();
    let mut total = 0usize;
    for (index, commit) in commits.iter().enumerate() {
        let patch = repo.commit_patch(&commit.sha)?;
        let files = parse_patch(&patch)?;
        for f in &files {
            *extensions.entry(extension_of(&f.path)).or_default() += 1;
        }
        let section = render_commit(index + 1, commit, &files, cfg, truncate);
        if !sections.is_empty() && total + section.len() > budget {
            break;
        }
        total += section.len();
        sections.push(section);
    }
    let mut stats: Vec<(String, usize)> = extensions.into_iter().collect();
    stats.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    let stats_text: Vec<String> = stats
        .iter()
        .take(10)
        .map(|(ext, n)| format!("{ext} ({n})"))
        .collect();
    let mut text = String::new();
    text.push_str(&format!(
        "Commits in the repository: {commits_available}. Shown below: the {} most recent non-merge commit(s), newest first.\n",
        sections.len()
    ));
    if !stats_text.is_empty() {
        text.push_str(&format!("File types touched: {}.\n", stats_text.join(", ")));
    }
    text.push_str(&format!(
        "Diff detail is reduced: at most {} files per commit and {} diff lines per file are shown.\n\n",
        cfg.max_files_per_commit, cfg.max_lines_per_file
    ));
    text.push_str(&sections.join("\n\n"));
    Ok(HistoryContext {
        commits_available,
        commits_included: sections.len(),
        text,
    })
}

fn extension_of(path: &str) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    match name.rsplit_once('.') {
        Some((stem, ext)) if !stem.is_empty() => ext.to_ascii_lowercase(),
        _ => "(no extension)".to_string(),
    }
}

fn truncate_line(line: &str, max_chars: Option<usize>) -> String {
    match max_chars {
        Some(n) if n > 0 && line.chars().count() > n => {
            let kept: String = line.chars().take(n).collect();
            format!("{kept}...")
        }
        _ => line.to_string(),
    }
}

fn file_summary(file: &FilePatch) -> String {
    let mut parts: Vec<String> = vec![file.kind.to_string()];
    if file.binary {
        parts.push("binary".into());
    }
    let header = String::from_utf8_lossy(&file.header);
    if let Some(from) = header.lines().find_map(|l| l.strip_prefix("rename from ")) {
        parts.push(format!("renamed from {from}"));
    }
    if let Some((old, new)) = &file.mode_change {
        parts.push(format!("mode {old} -> {new}"));
    }
    if !file.binary && !file.hunks.is_empty() && file.kind != FileKind::Submodule {
        parts.push(format!("+{} -{}", file.added(), file.removed()));
    }
    format!("### {} ({})", file.path, parts.join(", "))
}

/// Renders one commit: message, totals, and a few diff lines per file.
pub fn render_commit(
    number: usize,
    commit: &HistoryCommit,
    files: &[FilePatch],
    cfg: &InitConfig,
    truncate: Option<usize>,
) -> String {
    let mut out: Vec<String> = Vec::new();
    out.push(format!(
        "## Commit {number}: {} ({})",
        commit.short_sha, commit.date
    ));
    out.push("Message:".into());
    let message = commit.message.replace(WATERMARK, "");
    for line in message.trim().lines() {
        if line.trim().is_empty() {
            out.push(String::new());
        } else {
            out.push(format!("  {}", line.trim_end()));
        }
    }
    let added: u32 = files.iter().map(|f| f.added()).sum();
    let removed: u32 = files.iter().map(|f| f.removed()).sum();
    out.push(format!("Files ({}): +{added} -{removed}", files.len()));
    let shown = cfg.max_files_per_commit.max(1);
    for file in files.iter().take(shown) {
        out.push(file_summary(file));
        if file.binary {
            continue;
        }
        let mut lines: Vec<String> = Vec::new();
        let mut remaining = 0usize;
        for hunk in &file.hunks {
            for line in String::from_utf8_lossy(&hunk.text).lines() {
                if lines.len() < cfg.max_lines_per_file {
                    lines.push(truncate_line(line, truncate));
                } else {
                    remaining += 1;
                }
            }
        }
        out.extend(lines);
        if remaining > 0 {
            out.push(format!("... ({remaining} more diff lines)"));
        }
    }
    if files.len() > shown {
        let rest: Vec<&str> = files[shown..].iter().map(|f| f.path.as_str()).collect();
        out.push(format!(
            "... ({} more files: {})",
            rest.len(),
            rest.join(", ")
        ));
    }
    out.join("\n")
}

/// The user message for the rules model.
pub fn build_rules_context(repo_name: &str, branch: &str, history: &HistoryContext) -> String {
    format!(
        "Repository: {repo_name}\nBranch: {branch}\n{}",
        history.text
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> InitConfig {
        InitConfig {
            commits: 5,
            max_files_per_commit: 2,
            max_lines_per_file: 3,
            max_total_kb: 100,
        }
    }

    #[test]
    fn renders_commit_with_reduced_detail() {
        let diff = b"diff --git a/src/a.rs b/src/a.rs\nindex 1..2 100644\n--- a/src/a.rs\n+++ b/src/a.rs\n@@ -1,4 +1,6 @@\n-a\n+A\n+A2\n+A3\n b\n c\n d\ndiff --git a/old.txt b/new.txt\nsimilarity index 90%\nrename from old.txt\nrename to new.txt\nindex 1..2 100644\n--- a/old.txt\n+++ b/new.txt\n@@ -1 +1 @@\n-x\n+y\ndiff --git a/third.md b/third.md\nnew file mode 100644\nindex 0..1\n--- /dev/null\n+++ b/third.md\n@@ -0,0 +1 @@\n+hello\n";
        let files = parse_patch(diff).unwrap();
        let commit = HistoryCommit {
            sha: "abc".into(),
            short_sha: "abc1234".into(),
            date: "2026-10-19".into(),
            message: format!("feat: add thing\n\nbody line\n\n{WATERMARK}"),
        };
        let text = render_commit(1, &commit, &files, &cfg(), Some(40));
        assert!(text.starts_with("## Commit 1: abc1234 (2026-10-19)\nMessage:\n  feat: add thing\n\n  body line\nFiles (3): +5 -2\n"), "{text}");
        assert!(
            text.contains(
                "### src/a.rs (modified, +3 -1)\n@@ -1,4 +1,6 @@\n-a\n+A\n... (5 more diff lines)"
            ),
            "{text}"
        );
        assert!(
            text.contains("### new.txt (modified, renamed from old.txt, +1 -1)"),
            "{text}"
        );
        assert!(text.contains("... (1 more files: third.md)"), "{text}");
        assert!(!text.contains(WATERMARK));
    }

    #[test]
    fn parses_rules_response() {
        let r = parse_rules_response(
            "```json\n{\"observations\":[\"a\"],\"rules\":\"Use lowercase.\"}\n```",
        )
        .unwrap();
        assert_eq!(r.observations, vec!["a"]);
        assert_eq!(r.rules, "Use lowercase.");
        assert!(parse_rules_response("{\"observations\":[],\"rules\":\"  \"}").is_err());
    }

    #[test]
    fn extensions() {
        assert_eq!(extension_of("src/x/y.RS"), "rs");
        assert_eq!(extension_of("Makefile"), "(no extension)");
        assert_eq!(extension_of(".gitignore"), "(no extension)");
    }
}
